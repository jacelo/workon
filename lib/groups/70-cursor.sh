# cursor — open the project in Cursor over Remote-SSH, and close it on `workon --down`.
#
# "cursor": {
#   "open": true               // default true; false skips opening Cursor
# }
# Uses "workspace.file" when set, otherwise the workspace folder, and "vm.ssh_host" when set.
register_group cursor

cursor::load() {
  CURSOR_BIN="$(command -v cursor || echo /Applications/Cursor.app/Contents/Resources/app/bin/cursor)"
  SSH_HOST="$(field vm.ssh_host "")"
  [[ -n "$SSH_HOST" ]] || SSH_HOST="workon-$MACHINE"   # alias written by cursor_ssh_alias
}

cursor::open() {
  [[ "$(field cursor.open true)" == "true" ]] || return 0
  [[ -x "$CURSOR_BIN" ]] || die "Cursor CLI not found at $CURSOR_BIN"
  cursor_ssh_alias
  if [[ -n "$WORKSPACE_FILE" ]]; then
    local target; target="$(vm_path "$WORKSPACE_FILE")"
    info "Opening workspace $target on $SSH_HOST in Cursor…"
    "$CURSOR_BIN" --file-uri "vscode-remote://ssh-remote+${SSH_HOST}${target}"
  else
    info "Opening $PROJ_PATH on $SSH_HOST in Cursor…"
    "$CURSOR_BIN" --folder-uri "vscode-remote://ssh-remote+${SSH_HOST}${PROJ_PATH}"
  fi
}

cursor::down() { cursor_close_windows; }

# Cursor can't parse OrbStack's "user@machine@orb" hosts (it reads "machine@orb" as the
# hostname), so each machine gets a plain alias. Its settings are copied from OrbStack's own
# "orb" host on every run so they stay current. Aliases live in ~/.ssh/workon/*.conf.
cursor_ssh_alias() {
  [[ "$SSH_HOST" == "workon-$MACHINE" ]] || return 0   # your own vm.ssh_host: leave it alone
  local dir="$HOME/.ssh/workon" cfg="$HOME/.ssh/config" resolved
  local include="Include ~/.ssh/workon/*.conf"
  mkdir -p "$dir"; chmod 700 "$dir"
  resolved="$(ssh -G "${USER_NAME}@${MACHINE}@orb" 2>/dev/null)" ||
    die "Couldn't read OrbStack's SSH settings (ssh -G ${USER_NAME}@${MACHINE}@orb)"
  {
    echo "# AUTO-GENERATED BY workon — rewritten on every run."
    echo "Host $SSH_HOST"
    echo "  User ${USER_NAME}@${MACHINE}"
    awk '$1 ~ /^(hostname|port|identityfile|identitiesonly|userknownhostsfile|proxycommand)$/' <<<"$resolved" |
      sed -E 's/^hostname /  HostName /; s/^port /  Port /; s/^identityfile /  IdentityFile /;
              s/^identitiesonly /  IdentitiesOnly /; s/^userknownhostsfile /  UserKnownHostsFile /;
              s/^proxycommand /  ProxyCommand /'
    echo "  ForwardAgent no"
    echo "  ForwardX11 no"
  } > "$dir/$MACHINE.conf"
  chmod 600 "$dir/$MACHINE.conf"
  # The Include must come before any Host block in ~/.ssh/config, so it goes at the very top.
  if ! grep -qxF "$include" "$cfg" 2>/dev/null; then
    info "Adding '$include' to the top of $cfg"
    touch "$cfg"; chmod 600 "$cfg"
    { printf '# Added by workon: SSH aliases for project machines\n%s\n\n' "$include"; cat "$cfg"; } > "$cfg.workon.tmp"
    mv "$cfg.workon.tmp" "$cfg"
  fi
}

# Close Cursor windows connected to this machine (title contains "SSH: <host>"); others stay.
# Needs Accessibility permission for your terminal app, to click the window's close button.
cursor_close_windows() {
  local closed
  if ! closed="$(osascript - "SSH: $SSH_HOST" 2>&1 <<'APPLESCRIPT'
on run argv
  set pat to item 1 of argv
  tell application "System Events"
    if not (exists process "Cursor") then return 0
    tell process "Cursor"
      set n to 0
      repeat while (n < 20) and (exists (first window whose name contains pat))
        click (first button of (first window whose name contains pat) whose subrole is "AXCloseButton")
        set n to n + 1
        delay 0.5
      end repeat
      return n
    end tell
  end tell
end run
APPLESCRIPT
)"; then
    warn "Couldn't close the Cursor window automatically — close it yourself."
    warn "To allow it: System Settings › Privacy & Security › Accessibility › enable your terminal app."
    return 0
  fi
  if [[ "$closed" == "0" ]]; then info "No Cursor window open for $SSH_HOST"
  else ok "Closed $closed Cursor window(s) for $SSH_HOST"; fi
}
